def page_shell(slug: str, title: str, body: str) -> str:
    group = PAGE_BY_SLUG[slug][3]
    mins = PAGE_BY_SLUG[slug][4]
    css = "\n".join(f'<link rel="stylesheet" href="assets/{f}">' for f in CSS_FILES)
    js = "\n".join(f'<script src="assets/{f}" defer></script>' for f in JS_FILES)
    article_html = f"""<article class="page" data-page="{slug}">
{body}
{prevnext_html(slug, False)}
</article>"""
    shell = render_app_shell(slug, group, title, mins, article_html, False)
    return f"""<!doctype html>
<html lang="en" data-theme="carbon">
<head>
<meta charset="utf-8">
<title>{html.escape(title)} · {SITE_TITLE}</title>
{HEAD_EXTRA}
{css}
{js}
</head>
<body data-page="{slug}">
{shell}
</body>
</html>
"""


def inline_css() -> str:
    """All CSS inlined for single-file bundle."""
    return "\n".join((ASSETS / f).read_text() for f in CSS_FILES)


def inline_js(search_js: str) -> list[str]:
    out = []
    for f in JS_FILES:
        src = ASSETS / f
        out.append(src.read_text() if src.exists() else search_js)
    return out


def bundle_shell(sections: str, search_js: str) -> str:
    css = f"<style>{inline_css()}</style>"
    js = "\n".join(f"<script>{part}</script>" for part in inline_js(search_js))
    shell = render_app_shell("index", "Orientation", "Start here", 12, sections, True)
    return f"""<!doctype html>
<html lang="en" data-theme="carbon">
<head>
<meta charset="utf-8">
<title>{SITE_TITLE} · {SITE_TAGLINE}</title>
{HEAD_EXTRA}
{css}
</head>
<body data-page="index" data-spa="1">
{shell}
{js}
</body>
</html>
"""


def artifact_page(sections: str, search_js: str) -> str:
    """Body-only variant for hosts that supply their own <head> wrapper."""
    css = f"<style>{inline_css()}</style>"
    js = "\n".join(f"<script>{part}</script>" for part in inline_js(search_js))
    shell = render_app_shell("index", "Orientation", "Start here", 12, sections, True)
    return f"""<title>{SITE_TITLE} · {SITE_TAGLINE}</title>
{css}
<div id="aip-root" data-page="index" data-spa="1">
{shell}
</div>
<script>
document.body.dataset.spa = '1';
document.body.dataset.page = 'index';
</script>
{js}
"""


# --------------------------------------------------------------------------
# content post-processing
# --------------------------------------------------------------------------

SECTION_RE = re.compile(r'<section\b[^>]*\bid="([^"]+)"[^>]*>')
H2_RE = re.compile(r"<h2[^>]*>(.*?)</h2>", re.S)


NUM_SPAN_RE = re.compile(r'<span class="num">.*?</span>', re.S)


def strip_tags(s: str) -> str:
    s = NUM_SPAN_RE.sub("", s)
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", s)).strip()


def inject_read_toggles(body: str) -> str:
    """Add a 'mark as read' control to every top-level <section id=...>."""
    def repl(m: re.Match) -> str:
        sid = m.group(1)
        return m.group(0) + (
            f'<button class="read-toggle" data-read="{sid}" '
            f'title="Mark this section as read">'
            f'<span class="rt-box"></span><span class="rt-label">Mark read</span></button>'
        )
    return SECTION_RE.sub(repl, body)


def build_toc(body: str) -> str:
    items = []
    for m in SECTION_RE.finditer(body):
        sid = m.group(1)
        tail = body[m.end(): m.end() + 900]
        h = H2_RE.search(tail)
        if not h:
            continue
        items.append(f'<a href="#{sid}" data-toc="{sid}">{html.escape(strip_tags(h.group(1)))}</a>')
    if len(items) < 2:
        return ""
    return '<nav class="toc"><div class="toc-title">On this page</div>' + "".join(items) + "</nav>"


def render_body(slug: str, raw: str) -> str:
    title = PAGE_BY_SLUG[slug][2]
    group = PAGE_BY_SLUG[slug][3]
    mins = PAGE_BY_SLUG[slug][4]
    header = (
        f'<div class="page-head">'
        f'<div class="crumb">{html.escape(group)}</div>'
        f'<h1>{html.escape(title)}</h1>'
        f'<div class="page-meta"><span class="pill">≈{mins} min</span>'
        f'<span class="pill pill-ghost" id="pageReadState-{slug}">not started</span></div>'
        f"</div>"
    )
    toc = build_toc(raw)
    body = inject_read_toggles(raw)

    # A leading .hero block should sit above the table of contents.
    if toc and body.lstrip().startswith('<div class="hero">'):
        end = body.find("</div>\n\n<section")
        if end == -1:
            end = body.find("<section")
            return header + body[:end] + toc + body[end:]
        end += len("</div>")
        return header + body[:end] + toc + body[end:]
    return header + toc + body


def search_rows(slug: str, raw: str) -> list[dict]:
    """Flat search index so search works across pages in the multi-page build."""
    rows = []
    page_title = PAGE_BY_SLUG[slug][2]
    for m in SECTION_RE.finditer(raw):
        sid = m.group(1)
        nxt = SECTION_RE.search(raw, m.end())
        chunk = raw[m.end(): nxt.start() if nxt else len(raw)]
        h = H2_RE.search(chunk)
        rows.append({
            "slug": slug,
            "id": sid,
            "page": page_title,
            "group": PAGE_BY_SLUG[slug][3],
            "title": strip_tags(h.group(1)) if h else sid,
            "text": strip_tags(chunk)[:6000].lower(),
        })
    return rows


# --------------------------------------------------------------------------
# main
# --------------------------------------------------------------------------

def main() -> None:
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    shutil.copytree(ASSETS, OUT / "assets")
    (OUT / ".nojekyll").write_text("")

    bodies: dict[str, str] = {}
    index: list[dict] = []
    for slug, _label, title, _group, _mins in PAGES:
        src = CONTENT / f"{slug}.html"
        if not src.exists():
            print(f"  !! missing fragment, stubbing: {src.name}")
            raw = f'<section id="{slug}-todo"><h2>Coming up</h2><p>Not written yet.</p></section>'
        else:
            raw = src.read_text()
        index.extend(search_rows(slug, raw))
        bodies[slug] = render_body(slug, raw)
        (OUT / f"{slug}.html").write_text(page_shell(slug, title, bodies[slug]))

    search_js = "window.AIP_SEARCH = " + json.dumps(index, separators=(",", ":")) + ";\n"
    (OUT / "assets" / "data" / "searchindex.js").write_text(search_js)

    sections = []
    for slug, _label, _title, _group, _mins in PAGES:
        hidden = "" if slug == "index" else " hidden"
        sections.append(
            f'<article class="page" data-page="{slug}"{hidden}>\n'
            f"{bodies[slug]}\n{prevnext_html(slug, True)}\n</article>"
        )
    (OUT / "all-in-one.html").write_text(bundle_shell("\n".join(sections), search_js))
    (OUT / "artifact.html").write_text(artifact_page("\n".join(sections), search_js))

    total = sum(len(bodies[s].encode()) for s in bodies)
    print(f"built {len(PAGES)} pages -> {OUT}   search index: {len(index)} sections")
