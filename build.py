def nav_html(current: str, single_file: bool) -> str:
    """Sidebar navigation, grouped."""
    out = []
    seen_groups = []
    for slug, label, _title, group, mins in PAGES:
        if group not in seen_groups:
            seen_groups.append(group)
            out.append(f'<div class="nav-group" data-nav-group="{html.escape(group)}">{html.escape(group)}</div>')
        href = f"#/{slug}" if single_file else ("index.html" if slug == "index" else f"{slug}.html")
        cls = "nav-link active" if slug == current else "nav-link"
        out.append(
            f'<a class="{cls}" href="{href}" data-slug="{slug}">'
            f'<span class="nav-dot" data-dot="{slug}"></span>'
            f'<span class="nav-label">{html.escape(label)}</span>'
            f'<span class="nav-mins">{mins}m</span></a>'
        )
    return "\n".join(out)


def prevnext_html(current: str, single_file: bool) -> str:
    idx = [p[0] for p in PAGES].index(current)
    parts = ['<nav class="prevnext">']
    if idx > 0:
        s, lbl = PAGES[idx - 1][0], PAGES[idx - 1][1]
        href = f"#/{s}" if single_file else ("index.html" if s == "index" else f"{s}.html")
        parts.append(f'<a class="pn pn-prev" href="{href}"><span>← Previous</span><strong>{html.escape(lbl)}</strong></a>')
    else:
        parts.append("<span></span>")
    if idx < len(PAGES) - 1:
        s, lbl = PAGES[idx + 1][0], PAGES[idx + 1][1]
        href = f"#/{s}" if single_file else ("index.html" if s == "index" else f"{s}.html")
        parts.append(f'<a class="pn pn-next" href="{href}"><span>Next →</span><strong>{html.escape(lbl)}</strong></a>')
    else:
        parts.append("<span></span>")
    parts.append("</nav>")
    return "\n".join(parts)


